// Helper to get all unique communes across all 31 regions + 2 districts
export const ALL_CI_COMMUNES = Array.from(
  new Set(IVORY_COAST_REGIONS.flatMap((r) => r.communes))
).sort();

export function findRegionByCommune(communeName: string): RegionInfo | undefined {
  const norm = (communeName || '').trim().toLowerCase();
  if (!norm) return undefined;
  return IVORY_COAST_REGIONS.find((r) =>
    r.communes.some((c) => c.toLowerCase() === norm || norm.includes(c.toLowerCase()) || c.toLowerCase().includes(norm)) ||
    r.chefLieu.toLowerCase() === norm ||
    r.name.toLowerCase() === norm ||
    norm.includes(r.name.toLowerCase())
  );
}

export function getRegionByNameOrLabel(label: string): RegionInfo | undefined {
  if (!label || label === 'Toutes les régions') return undefined;
  const clean = label.trim().toLowerCase();

  return IVORY_COAST_REGIONS.find((r) => {
    const formatted = r.isAutonomousDistrict
      ? `${r.name} (District Autonome)`.toLowerCase()
      : `${r.name} (${r.chefLieu})`.toLowerCase();
    
    return (
      clean === r.name.toLowerCase() ||
      clean === r.chefLieu.toLowerCase() ||
      clean === formatted ||
      clean.startsWith(r.name.toLowerCase()) ||
      clean.includes(r.name.toLowerCase()) ||
      r.name.toLowerCase().includes(clean)
    );
  });
}
